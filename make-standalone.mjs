import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const read=name=>fs.readFileSync(path.join(root,'dist',name),'utf8');
const styles=read('style.css');
const physics=read('physics.js').replace(/^export /gm,'');
const application=read('app.js').replace(/^import .*?;\r?\n/,'');
const mixingPhysics=read('mixing-physics.js').replace(/^export /gm,'');
const mixingApplication=read('mixing-ui.js').replace(/^import .*?;\r?\n/,'');
const prompt=read('implementation-prompt.txt');
let html=read('index.html');
html=html.replace('<link rel="stylesheet" href="style.css">',`<style>${styles}</style>`);
html=html.replace('<link rel="stylesheet" href="mixing.css">',`<style>${read('mixing.css')}</style>`);
html=html.replace('<script type="module" src="app.js"></script>','').replace('<script type="module" src="mixing-ui.js"></script>','');
html=html.replace('href="implementation-prompt.txt"',`href="data:text/plain;charset=utf-8,${encodeURIComponent(prompt)}"`);
html=html.replace('href="mixing-specification.txt"',`href="data:text/plain;charset=utf-8,${encodeURIComponent(read('mixing-specification.txt'))}"`);
html=html.replace('</body>',`<script type="module">\n(()=>{\n${physics}\n${application}\n})();\n(()=>{\n${mixingPhysics}\n${mixingApplication}\n})();\n</script></body>`);
fs.writeFileSync(path.join(root,'dist','standalone.html'),html,'utf8');
console.log('Created dist/standalone.html — open directly in a modern browser; no server required.');
